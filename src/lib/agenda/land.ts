/** Punto en polígono (par-impar). */
export function inRing(lon: number, lat: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

export const isLand = (lon: number, lat: number): boolean => LAND.some((r) => inRing(lon, lat, r)) && !WATER.some((r) => inRing(lon, lat, r));

/** Proyección equirectangular recortada (lon -170..180, lat 82..-58) a un viewBox de 1000 x 400. */
export function project(lat: number, lon: number): { x: number; y: number } {
  const x = ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * MAP_W;
  const y = ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * MAP_H;
  return { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
}

/** Centros de celda (en grados) de la trama de puntos que caen en tierra. */
export function landCells(step = 3): { lon: number; lat: number }[] {
  const out: { lon: number; lat: number }[] = [];
  for (let lat = LAT_MAX - step / 2; lat > LAT_MIN; lat -= step) {
    for (let lon = LON_MIN + step / 2; lon < LON_MAX; lon += step) if (isLand(lon, lat)) out.push({ lon, lat });
  }
  return out;
}

let dots: string | null = null;
/** Tierra como un único `d` de trazo (puntos de largo cero con extremos redondos): liviano y sin una etiqueta por punto. */
export function landDots(step = 3): string {
  if (step === 3 && dots) return dots;
  const d = landCells(step)
    .map(({ lon, lat }) => {
      const p = project(lat, lon);
      return `M${p.x} ${p.y}h0`;
    })
    .join('');
  if (step === 3) dots = d;
  return d;
}

/** Meridianos y paralelos cada `every` grados como un único `d`. */
export function graticule(every = 30): string {
  const parts: string[] = [];
  for (let lon = Math.ceil(LON_MIN / every) * every; lon <= LON_MAX; lon += every) {
    const a = project(LAT_MAX, lon);
    const b = project(LAT_MIN, lon);
    parts.push(`M${a.x} ${a.y}V${b.y}`);
  }
  for (let lat = Math.floor(LAT_MAX / every) * every; lat >= LAT_MIN; lat -= every) {
    const a = project(lat, LON_MIN);
    const b = project(lat, LON_MAX);
    parts.push(`M${a.x} ${a.y}H${b.x}`);
  }
  return parts.join('');
}
